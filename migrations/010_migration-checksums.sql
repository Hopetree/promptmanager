-- 阶段 69 / FR-144（设计评审 F11）：给 schema_migrations 加**内容校验**列。
--
-- 问题：schema_migrations 原本只有 (version, name, applied_at)，迁移运行器只按数字前缀判断
-- "这一版跑过没有"。于是**一个已经应用过的迁移被改动，没有任何机制发现** —— 两份库的
-- schema 会悄悄分叉，而"迁移幂等由版本表保证"这套机制救不了它（版本号没变、内容变了）。
--
-- 做法：加一个可空的 checksum 列（sha256 of 文件原始字节），由 src/db/migrate.ts 负责
--   ① 应用迁移时写入；
--   ② 每次迁移前/后比对已应用迁移的内容，不符即**明确失败**（报出文件名与期望/实际 hash）。
--
-- 为什么可空：本迁移之前应用的 001–009 没有 hash。存量口径 = **首次见到时补记**（运行器回填），
-- 不是"存量不校验"—— 这样老库升级后立刻进入受校验状态，且升级本身不会失败。
--
-- 为什么是新迁移而不是改 001：001 已经在别人的库上跑过了，改它会让两份库的 schema 悄悄分叉
-- ——正是本迁移要检测的那种事故。
ALTER TABLE schema_migrations ADD COLUMN checksum TEXT;
