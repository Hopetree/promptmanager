-- 008_remember-variables.sql —— 阶段 61 / FR-127 / D-59：变量记忆「可控」（每个提示词一个开关）
--
-- 背景（用户 2026-10-09 原话「目前的每个提示词都会自动记住上一次填写的变量值，但是实际上
-- 有的提示词不需要记住，应该保持每次都是新的，所以我的需求是有勾选项可以来给每个提示词
-- 设置是否要记住变量」）：
-- 给 `prompts` 加一列「是否记住变量值」，让每个提示词各自决定。
--
-- 为什么放服务端而不是 localStorage（D-59 ①）：它是提示词的属性（与 `favorite` 同类），
-- 放服务端才能**换浏览器 / 换设备一致**，并且**随导出 / 导入 / 远程同步一起走**；
-- 放前端会出现「电脑上设了不记住、手机还在记」。
--
-- ⚠️ 变量值本身**仍然只存在浏览器 localStorage**（键 `pm-vars:<id>`，FR-41e 既有口径）——
--    本列只控制"要不要记"，**不把变量值搬上服务端**（D-59 ⑦：那是另一个量级的改动，且涉及隐私面）。
--
-- 默认「记住」（= 1）：存量提示词与既有行为**一字不变**（D-59 ②，用户拍板）。
--
-- 幂等：由 schema_migrations 记录版本号保证只执行一次（与 001–007 同一机制）。
-- `ALTER TABLE ADD COLUMN` 带 `NOT NULL DEFAULT 1`：SQLite 允许（默认值非 NULL 即可），
-- 且**存量行一律被填成 1** ⇒ AC-123 ① 的「已有数据的库执行后所有存量都 = 记住」由数据库层保证。
-- `CHECK` 把"只能是 0/1"变成数据库层约束，而不是只靠应用层自觉。

ALTER TABLE prompts ADD COLUMN remember_variables INTEGER NOT NULL DEFAULT 1
  CHECK (remember_variables IN (0, 1));
